# include <iostream>
using namespace std;
int main(){
    int a , b;
    cout << "enter a : ";
    cin >> a;

    cout << "enter b : ";
    cin >> b;


    cout << "the sum of the two numbers is: " << a + b<< "\n";
    cout << "the difference of the two numbers is: " << a - b << "\n";
    cout << "the product of the two numbers is: " << a * b << "\n";
    cout << "the division of the two numbers is: " << a / b << "\n";
    cout << "the remainder of the two numbers is: " << a % b << "\n";
    return 0;
}
